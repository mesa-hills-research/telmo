"""Generate the data files of the Rust port of Whisper's multilingual text normalizer.

Usage: python -I gen_basic.py <basic.py> <commit> <wer dir> [<list.tsv> <hypotheses.tsv>]...

<basic.py> is whisper/normalizers/basic.py from github.com/openai/whisper at <commit> (MIT).
Writes into <wer dir>:
- unicode-nfkc.tsv, what NFKC needs from this Python's unicodedata, namely every character's full
  compatibility decomposition, the canonical combining classes and the canonical compositions,
- basic-vectors.tsv, inputs and BasicTextNormalizer()'s output for them, the inputs being hand-written lines,
  runs of every character the NFKC tables name, and the reference and hypothesis of the first
  ten utterances of each list given (a list has `id<TAB>wav<TAB>reference`, a hypothesis file
  `id<TAB>text`).
"""

import importlib.util
import os
import sys
import types
import unicodedata

basic_path, commit, out_dir = sys.argv[1:4]
pairs = sys.argv[4:]
assert len(pairs) % 2 == 0

# basic.py imports `regex` for split_letters, which the default normalizer never uses.
sys.modules["regex"] = types.ModuleType("regex")
spec = importlib.util.spec_from_file_location("basic", basic_path)
basic = importlib.util.module_from_spec(spec)
spec.loader.exec_module(basic)
normalizer = basic.BasicTextNormalizer()

SOURCE = f"whisper/normalizers/basic.py in github.com/openai/whisper at commit {commit} (MIT)"
UNICODE = f"Python {sys.version.split()[0]} unicodedata (Unicode {unicodedata.unidata_version})"
HANGUL = range(0xAC00, 0xD7A4)


def code_points():
    for cp in range(0x110000):
        if not (0xD800 <= cp <= 0xDFFF):
            yield cp


decompositions = {}
classes = {}
compositions = []
for cp in code_points():
    c = chr(cp)
    if cp not in HANGUL:
        d = unicodedata.normalize("NFKD", c)
        if d != c:
            decompositions[cp] = [ord(x) for x in d]
    k = unicodedata.combining(c)
    if k:
        classes[cp] = k
    mapping = unicodedata.decomposition(c) if cp not in HANGUL else ""
    if mapping and not mapping.startswith("<"):
        parts = [int(p, 16) for p in mapping.split()]
        # A primary composite has two parts, and NFC keeps it (it isn't excluded from composition).
        if len(parts) == 2 and unicodedata.normalize("NFC", c) == c:
            compositions.append((parts[0], parts[1], cp))

with open(os.path.join(out_dir, "unicode-nfkc.tsv"), "w", encoding="utf-8", newline="\n") as f:
    f.write(f"# NFKC data for basic.rs, from {UNICODE}, generated by scripts/gen_basic.py\n")
    f.write("# d <code point> <code points...> is a character's full compatibility decomposition. Hangul syllables are computed\n")
    f.write("# k <first>[-<last>] <class> is the canonical combining class of a run, 0 elsewhere\n")
    f.write("# p <first> <second> <composite> is a canonical composition. Hangul syllables are computed\n")
    for cp, d in decompositions.items():
        f.write("d %x %s\n" % (cp, " ".join("%x" % x for x in d)))
    run = None
    for cp in sorted(classes):
        if run and run[1] == cp - 1 and run[2] == classes[cp]:
            run[1] = cp
            continue
        if run:
            f.write("k %s %d\n" % (("%x" % run[0]) if run[0] == run[1] else "%x-%x" % (run[0], run[1]), run[2]))
        run = [cp, cp, classes[cp]]
    f.write("k %s %d\n" % (("%x" % run[0]) if run[0] == run[1] else "%x-%x" % (run[0], run[1]), run[2]))
    for a, b, c in compositions:
        f.write("p %x %x %x\n" % (a, b, c))


def escape(s):
    """Backslash escapes for the vector file, as gen_vectors.py writes them."""
    out = []
    for i, ch in enumerate(s):
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == " " and (i == 0 or i == len(s) - 1):
            out.append("\\u{20}")
        elif ch != " " and (not ch.isprintable() or ch.isspace()):
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


inputs = [
    "",
    " ",
    "Hello, World!",
    "  Leading and trailing  ",
    "tabs\tand\nnew\r\nlines",
    "[noise] words <unk> more [unclosed",
    "a (parenthesized words) b () c (unclosed",
    "<a [b> c] d",
    "é composed, ȩ́ reordered, ȩ́ too",
    "ǟ stacked, Å ring, Å angstrom",
    "각 jamo, 가 and 힣, 각 syllable plus final",
    "ｶﾞﾊﾟ half-width kana, ガ combining voiced mark",
    "ＡＢＣ１２３ full-width, 　ideographic space",
    "ﬁ ligature ① circled ½ half ™ trade ㎡ square",
    "ÉCOLE À PART È STATO İstanbul ΣΟΦΟΣ",
    "Große Straße ẞ œuvre æ ø łódź",
    "日本語のテキスト。「引用」（括弧）、点",
    "السلام عليكم किताब สวัสดี",
    "emoji \U0001F600 \U0001F468‍\U0001F469‍\U0001F467 \U0001F1FA\U0001F1F8 keycap 1️⃣",
    "quotes “double” ‘single’ «guillemets» „low“",
    "dashes – — hyphen-minus ‐ and − minus, 5% $3.50 €10",
    "soft­hyphen zero​width non breaking",
    "́ leading mark and trailing mark é",
    "กำ thai sara am, ཷ tibetan, ẛ̣ long s",
    "\U0001d400\U0001d41a math bold, \U0001d7ce digits",
    "Ω ohm K kelvin µ micro μ mu",
]

# Every character the tables name, in runs, so each decomposes, reorders and composes in context.
named = sorted(set(decompositions) | set(classes) | {x for p in compositions for x in p})
named += list(range(0xAC00, 0xAC00 + 600, 7)) + list(range(0x1100, 0x1200))
for i in range(0, len(named), 24):
    inputs.append("".join(chr(c) for c in named[i : i + 24]))
# Base letters with each combining mark, which is where composition happens.
marks = [cp for cp in sorted(classes) if cp < 0x10000]
for i in range(0, len(marks), 12):
    inputs.append(" ".join("a" + chr(m) + "e" + chr(m) + "o" for m in marks[i : i + 12]))

texts = 0
for lst, hyps in zip(pairs[0::2], pairs[1::2]):
    hyp = dict(line.rstrip("\n").split("\t", 1) for line in open(hyps, encoding="utf-8") if "\t" in line)
    for line in list(open(lst, encoding="utf-8"))[:10]:
        utt, _wav, reference = line.rstrip("\n").split("\t")
        inputs.append(reference)
        if utt in hyp:
            inputs.append(hyp[utt])
        texts += 1

seen = set()
count = 0
with open(os.path.join(out_dir, "basic-vectors.tsv"), "w", encoding="utf-8", newline="\n") as f:
    f.write(
        f"# Input and BasicTextNormalizer()'s output, tab-separated, with backslash escapes. From {SOURCE} "
        f"and {UNICODE}, generated by scripts/gen_basic.py. The lines after the hand-written ones and the character "
        "runs are references of FLEURS (google/fleurs, CC BY 4.0) and transcripts of them by Granite Speech 5.0 "
        "470M TurboCTC (Apache-2.0).\n"
    )
    for text in inputs:
        if text in seen:
            continue
        seen.add(text)
        f.write(escape(text) + "\t" + escape(normalizer(text)) + "\n")
        count += 1
print(f"{len(decompositions)} decompositions, {len(classes)} combining classes, {len(compositions)} compositions, "
      f"{count} vectors ({texts} utterances)")
