"""Generate english-2026.tsv and normalize-2026-vectors.tsv for the 2026 version of the leaderboard's
English normalizer.

Usage: python -I gen_tables_2026.py <leaderboard dir 2025> <leaderboard dir 2026> <commit 2026> <wer dir>

Each leaderboard dir holds the `normalizer/` package of github.com/huggingface/open_asr_leaderboard,
at commit 6a3e6d4e (2025) and at <commit 2026>. Writes into <wer dir>:
- english-2026.tsv, how the 2026 spelling map differs from the 2025 one, and the name map,
- normalize-2026-vectors.tsv, the inputs of normalize-vectors.tsv and lines for every rule and table
  entry the 2026 version adds, with the 2026 normalizer's output for each.
The filler and compound patterns are written out in normalize.rs, so this script checks that the
Python source still has the ones it ports.
"""

import importlib
import os
import sys
import types
import unicodedata

old_dir, new_dir, commit, out_dir = sys.argv[1:5]

# normalizer.py imports `regex`, which only the multilingual normalizer uses.
sys.modules.setdefault("regex", types.ModuleType("regex"))


def load(name, path):
    """Imports normalizer.py and english_abbreviations.py as package `name`, without its __init__."""
    package = types.ModuleType(name)
    package.__path__ = [os.path.join(path, "normalizer")]
    sys.modules[name] = package
    return (
        importlib.import_module(f"{name}.normalizer"),
        importlib.import_module(f"{name}.english_abbreviations"),
    )


_, old_abbr = load("lb2025", old_dir)
new_norm, new_abbr = load("lb2026", new_dir)
normalizer = new_norm.EnglishTextNormalizer()

FILLERS = (
    r"\b(ah-ha|a+h+m*|a+h+a+|e+h+m*|e+m+|e+r+m*|h+a+h+|h+e+h+|h+m+|h+u+h+|m{2,}|m+h+m*|t+s+k+|u+g+h+|u+h+m*"
    r"|u+h+u+[hm]*|u+m+h*|ahem|eheh|ehehe|ehr|hmmph|hum|hunh|mhum|mmkay)\b"
)
assert normalizer.ignore_patterns == FILLERS, normalizer.ignore_patterns
PAIRS = [
    ("et", "cetera", "etc"), ("al", "right", "alright"), ("all", "right", "alright"), ("how", "ever", "however"),
    ("wi", "fi", "wifi"), ("hi", "fi", "hifi"), ("lo", "fi", "lofi"), ("sci", "fi", "scifi"), ("e", "mail", "email"),
    ("e", "book", "ebook"), ("e", "commerce", "ecommerce"), ("x", "ray", "xray"), ("t", "shirt", "tshirt"),
    ("a", "m", "am"), ("p", "m", "pm"), ("o", "k", "okay"),
]
COMPOUNDS = {rf"\b{a}\s+{b}\b": c for a, b, c in PAIRS} | {r"\bo+h+\b": "oh", r"\booo+\b": "oh"}
assert list(normalizer.compound_words.items()) == list(COMPOUNDS.items()), normalizer.compound_words
replacers = list(normalizer.replacers.items())
assert replacers[0] == (r"\b(\d{1,2}):00\b", r"\1"), replacers[0]
IS = r"\b(it|he|she|what|that|who|here|there|how|when|where|why|this)'s\b"
assert (IS, r"\1 is") in replacers

old_spell = old_abbr.english_spelling_normalizer
new_spell = new_abbr.english_spelling_normalizer
names = new_abbr.english_name_normalizer
SOURCE = f"github.com/huggingface/open_asr_leaderboard normalizer/english_abbreviations.py at commit {commit} (Apache-2.0)"
with open(os.path.join(out_dir, "english-2026.tsv"), "w", encoding="utf-8", newline="\n") as f:
    f.write(f"# Spellings and names of {SOURCE}, generated by scripts/gen_tables_2026.py\n")
    f.write("# s<TAB>word<TAB>spelling adds or changes an entry of english-spelling.tsv, x<TAB>word removes one, "
            "n<TAB>name<TAB>canonical name is an entry of the name map\n")
    for key, value in new_spell.items():
        if old_spell.get(key) != value:
            f.write(f"s\t{key}\t{value}\n")
    for key in old_spell:
        if key not in new_spell:
            f.write(f"x\t{key}\n")
    for key, value in names.items():
        assert "\t" not in key + value and "\n" not in key + value
        f.write(f"n\t{key}\t{value}\n")


def unescape(field):
    out, i = [], 0
    while i < len(field):
        c = field[i]
        if c != "\\":
            out.append(c)
            i += 1
            continue
        n = field[i + 1]
        if n == "u":
            end = field.index("}", i)
            out.append(chr(int(field[i + 3 : end], 16)))
            i = end + 1
            continue
        out.append({"\\": "\\", "t": "\t", "n": "\n", "r": "\r"}[n])
        i += 2
    return "".join(out)


def escape(s):
    """Backslash escapes for the vector files, as gen_vectors.py writes them."""
    out = []
    for i, ch in enumerate(s):
        if ch == "\\":
            out.append("\\\\")
        elif ch == "\t":
            out.append("\\t")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == " " and (i == 0 or i == len(s) - 1):
            out.append("\\u{20}")
        elif ch != " " and (not ch.isprintable() or ch.isspace()):
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


inputs = []
for line in open(os.path.join(out_dir, "normalize-vectors.tsv"), encoding="utf-8"):
    if line.startswith("#"):
        continue
    inputs.append(unescape(line.rstrip("\n").split("\t")[0]))

# Every rule and table entry the 2026 version adds, alone and in context.
fillers = [
    "ah-ha", "ah-hah", "ah-ha-ha", "uh-huh", "um-hmm", "mm-hmm", "ah", "aah", "ahh", "ahhh", "ahm", "ahmm", "aha",
    "ahaa", "eh", "ehh", "eeeh", "ehm", "em", "emm", "er", "err", "errr", "erm", "hah", "hahh", "heh", "hm", "hmm",
    "hmmm", "hhm", "huh", "huhh", "mm", "mmm", "mmmm", "m", "mh", "mhm", "mhmm", "mmhm", "tsk", "tsktsk", "ugh",
    "uuugh", "uh", "uuh", "uhh", "uuuh", "uhm", "uuuhm", "uhuh", "uhum", "uhuhm", "um", "umm", "ummm", "uuum", "umh",
    "ahem", "eheh", "ehehe", "ehr", "hmmph", "hum", "hunh", "mhum", "mmkay", "aham", "ahah", "hmmmph", "humm",
    "eh?", "Uh, I think, um... yes", "ERM, well", "uh1", "uh_", "uhé", "a hmm b", "hmm-hmm", "ah--ha", "ah- ha",
]
for f in fillers:
    inputs += [f, f"so {f} we go", f"{f}, {f}", f.upper() + "!"]
times = ["2:00", "2:00 AM", "at 3:00 pm", "11:00", "12:00pm", "123:00", "1:000", "01:00", "9:00.", "x9:00",
         "10:00:00", "4:30", "the 5:00 train", "٣:00", "1:00-2:00", "1, 2:00", "7 :00", "8: 00"]
inputs += times
for w in ["it", "he", "she", "what", "that", "who", "here", "there", "how", "when", "where", "why", "this",
          "john", "let", "it'", "the", "His", "Where"]:
    inputs += [f"{w}'s", f"{w}'s good", f"{w} 's", f"{w}’s"]
for a, b, c in PAIRS:
    inputs += [f"{a} {b}", f"{a}-{b}", f"{a.upper()}-{b}!", f"{a}  {b}", f"the {a} {b} here", f"{a}{b}",
               f"{a} {b}s", f"x{a} {b}", f"{a} {b} {b}", f"{c}"]
inputs += ["oh", "ohh", "ooh", "oohhh", "ohio", "ooo", "oooo", "oo", "o", "o h", "oh oh", "oh, oh", "oh-oh"]
oh = ["four oh one", "nineteen oh five", "oh seven nine eight", "oh seven", "oh", "oh oh", "oh my god",
      "room four oh", "four oh", "oh four oh", "twenty oh one", "oh 20 1", "20 oh 1", "oh twenty one", "zero seven",
      "o seven nine", "one oh oh seven", "$ oh five six", "five oh six seven", "oh one two", "oh one", "it's oh nine"]
inputs += oh + [s.capitalize() + "." for s in oh]
acronyms = ["b b c", "the b b c news", "5 g", "a b c", "i b m", "a big cat", "i a", "a i", "a i b", "x y", "x",
            "a", "1 2 3", "u s a", "u.s.a.", "u. s. a.", "a b", "i i i", "b-b-c", "t v show", "é f", "_ a", "½ g",
            "a ½", "ab c d", "c d ab", "e f g h i j"]
inputs += acronyms
for key in list(new_spell)[:5] + [k for k in new_spell if old_spell.get(k) != new_spell[k]]:
    inputs += [key, f"the {key} one"]
for key in names:
    inputs += [key, f"{key} said", key.capitalize()]

# Characters at every boundary of the classes the normalizer tests, as one-character words, which
# the acronym rule joins when they are letters or digits.
special = set()
prev = None
for c in range(0x110000):
    if 0xD800 <= c < 0xE000:
        continue
    ch = chr(c)
    key = (unicodedata.category(ch), ch.isspace(), ch.isalnum(), ch.isdecimal(), ch.lower() != ch)
    if key != prev:
        special.update([c, c - 1])
    prev = key
special = sorted(c for c in special if c > 0 and not 0xD800 <= c < 0xE000)
for i in range(0, len(special), 24):
    chunk = [chr(c) for c in special[i : i + 24]]
    inputs.append(" ".join(chunk))
    inputs.append("x " + " a ".join(chunk) + " 1")

seen, count = set(), 0
with open(os.path.join(out_dir, "normalize-2026-vectors.tsv"), "w", encoding="utf-8", newline="\n") as f:
    f.write("# Input and the 2026 leaderboard normalizer's output, tab-separated, with backslash escapes. "
            f"Generated by scripts/gen_tables_2026.py with the leaderboard at commit {commit}.\n")
    for text in inputs:
        if text in seen:
            continue
        seen.add(text)
        f.write(escape(text) + "\t" + escape(normalizer(text)) + "\n")
        count += 1
print(f"english-2026.tsv written, normalize-2026-vectors.tsv: {count} vectors")
