"""Generate the data files of the Rust port of the Open ASR leaderboard's English normalizer.

Usage: python -I gen_tables.py <leaderboard dir> <commit> <output dir>

<leaderboard dir> holds the leaderboard's `normalizer/` package. Writes
english-spelling.tsv (the British to American spelling map) and
unicode-classes.tsv (character classes and the per-character output of
remove_symbols_and_diacritics) into <output dir>.
"""

import sys
import unicodedata

src_dir, commit, out_dir = sys.argv[1], sys.argv[2], sys.argv[3]
sys.path.insert(0, src_dir)

from normalizer.english_abbreviations import english_spelling_normalizer  # noqa: E402
from normalizer.normalizer import remove_symbols_and_diacritics  # noqa: E402

KEEP = ".%$¢€£"
SOURCE = (
    "github.com/huggingface/open_asr_leaderboard normalizer/{file} at commit "
    + commit
    + " (Apache-2.0)"
)

# The spelling map, in the order of the source dict.
with open(f"{out_dir}/english-spelling.tsv", "w", encoding="utf-8", newline="\n") as f:
    f.write(
        "# British to American spellings from "
        + SOURCE.format(file="english_abbreviations.py")
        + ", generated by scripts/gen_tables.py\n"
    )
    for british, american in english_spelling_normalizer.items():
        assert british and american
        # A key with a space ("flyer / flier") never matches a single word,
        # but the file keeps it as the source has it.
        assert "\t" not in british + american and "\n" not in british + american
        assert british == british.strip() and not british.startswith("#")
        f.write(f"{british}\t{american}\n")


def char_class(ch):
    """One letter per class, giving what the normalizer's regexes and removal steps need to know."""
    cat = unicodedata.category(ch)
    if ch.isspace():
        return "z"  # \s and str.split()
    if ch.isdecimal():
        return "d"  # \d, also a word character
    if ch.isalnum():
        return "w"  # \w (with "_", handled in code)
    if cat == "Mn":
        return "n"  # removed by remove_symbols_and_diacritics
    if cat[0] in "MSP":
        return cat[0].lower()  # replaced with a space
    return "o"


def class_rule(ch, cls):
    """What remove_symbols_and_diacritics does to a character with no decomposition."""
    if ch in KEEP:
        return ch
    if cls == "n":
        return ""
    if cls in "msp":
        return " "
    return ch


# Checks the Rust port relies on.
for c in range(0x110000):
    ch = chr(c)
    cat = unicodedata.category(ch)
    assert ch.isalnum() == (cat[0] in "LN")
    assert ch.isdecimal() == (cat == "Nd")
    assert not (ch.isspace() and cat[0] in "LNMSP")
    # Canonical reordering only moves marks, which all become "" or " ",
    # so applying the removal character by character gives the same result.
    if unicodedata.combining(ch):
        assert cat[0] == "M"
    if ch.isdecimal() and unicodedata.decimal(ch) == 0:
        for k in range(10):
            assert unicodedata.decimal(chr(c + k)) == k

classes = []
prev = None
for c in range(0x110000):
    cls = char_class(chr(c))
    if cls != prev:
        classes.append((c, cls))
        prev = cls

# Each run of decimal digits must start at a zero, so a digit's value is its
# offset from the start of its run, modulo 10.
for i, (start, cls) in enumerate(classes):
    if cls == "d":
        end = classes[i + 1][0] if i + 1 < len(classes) else 0x110000
        assert (end - start) % 10 == 0
        for c in range(start, end):
            assert unicodedata.decimal(chr(c)) == (c - start) % 10

def hangul(c):
    """The decomposition of a Hangul syllable, which normalize.rs computes rather than looks up."""
    s = c - 0xAC00
    out = chr(0x1100 + s // 588) + chr(0x1161 + (s % 588) // 28)
    if s % 28:
        out += chr(0x11A7 + s % 28)
    return out


replacements = []
for c in range(0x110000):
    if 0xD800 <= c < 0xE000:
        continue  # surrogates, which a Rust string can't hold
    ch = chr(c)
    out = remove_symbols_and_diacritics(ch, keep=KEEP)
    if 0xAC00 <= c <= 0xD7A3:
        assert out == hangul(c)
        continue
    if out != class_rule(ch, char_class(ch)):
        replacements.append((c, out))

# Runs of consecutive code points become one line, "a-b x" when they all give
# x and "a-b +x" when they give x, x + 1 and so on.
runs = []
for c, out in replacements:
    if runs:
        start, end, first, step = runs[-1]
        if c == end + 1 and len(out) == 1 and len(first) == 1:
            if step in (None, 0) and out == first:
                runs[-1] = (start, c, first, 0)
                continue
            if step in (None, 1) and ord(out) == ord(first) + (c - start):
                runs[-1] = (start, c, first, 1)
                continue
    runs.append((c, c, out, None))

# Runs of code points that str.lower() changes.
lowered = []
for c in range(0x110000):
    if 0xD800 <= c < 0xE000 or chr(c).lower() == chr(c):
        continue
    if lowered and lowered[-1][1] == c - 1:
        lowered[-1] = (lowered[-1][0], c)
    else:
        lowered.append((c, c))

with open(f"{out_dir}/unicode-classes.tsv", "w", encoding="utf-8", newline="\n") as f:
    f.write(
        "# Character data for normalize.rs, from Python "
        + sys.version.split()[0]
        + " unicodedata (Unicode "
        + unicodedata.unidata_version
        + ") and remove_symbols_and_diacritics in "
        + SOURCE.format(file="normalizer.py")
        + ", generated by scripts/gen_tables.py\n"
    )
    f.write(
        "# c <first code point> <class> sets the class up to the next c line. z space, d decimal digit, "
        "w other letter or number, n nonspacing mark, m other mark, s symbol, p punctuation, o other\n"
    )
    f.write(
        "# r <code point> <code points...> is what the symbol and diacritic removal turns a character into "
        "(its compatibility decomposition, cleaned) where that differs from its class's rule. "
        "r <first>-<last> <code point> covers a run that all give that code point, "
        "and r <first>-<last> +<code point> a run that counts up from it. Hangul syllables are computed\n"
    )
    f.write("# l <first>[-<last>] is a run of characters that str.lower() changes\n")
    for start, cls in classes:
        f.write(f"c {start:x} {cls}\n")
    for first, last in lowered:
        f.write(f"l {first:x}\n" if first == last else f"l {first:x}-{last:x}\n")
    for start, end, out, step in runs:
        head = f"r {start:x}" if start == end else f"r {start:x}-{end:x}"
        if step == 1:
            f.write(f"{head} +{ord(out):x}\n")
        else:
            f.write(head + "".join(f" {ord(x):x}" for x in out) + "\n")

print(
    f"{len(english_spelling_normalizer)} spellings, {len(classes)} class ranges, "
    f"{len(replacements)} replacements in {len(runs)} lines, {len(lowered)} lowercase runs"
)
